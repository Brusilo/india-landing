#!/usr/bin/env node
/**
 * Builds assets/kite-tokens.css from the official Tutu token package
 * @tutu/mother-of-tokens (Kite design system).
 *
 * The package lives in Tutu's internal registry. To refresh the tokens:
 *
 *   npm pack @tutu/mother-of-tokens --registry=https://artifactory.tutu.ru/artifactory/api/npm/npm-common/
 *   tar -xzf tutu-mother-of-tokens-*.tgz
 *   node scripts/build-kite-tokens.js ./package
 *
 * Only the light theme is taken (the landing has no dark theme), and the
 * SCSS-only scales (radius, spacing, sizing) are turned into CSS variables.
 */
const fs = require('fs');
const path = require('path');

const pkgDir = process.argv[2];
if (!pkgDir) {
  console.error('Usage: node scripts/build-kite-tokens.js <path to unpacked @tutu/mother-of-tokens>');
  process.exit(1);
}

const pub = path.join(pkgDir, 'styles/public');
const read = f => fs.readFileSync(path.join(pub, f), 'utf8');
const version = JSON.parse(fs.readFileSync(path.join(pkgDir, 'package.json'), 'utf8')).version;

// The first rule block of each file is the light theme on :root.
const firstRootBlock = css => {
  const start = css.indexOf(':root');
  const open = css.indexOf('{', start);
  const close = css.indexOf('}', open);
  return css.slice(open + 1, close).trim().split('\n').map(l => '  ' + l.trim()).join('\n');
};

// "$radius-500: 16px;" -> "--kite-radius-500: 16px;"
const scssScale = (css, name) =>
  css.split('\n')
    .map(l => l.trim())
    .filter(l => l.startsWith('$' + name + '-') && l.endsWith(';'))
    .map(l => '  --kite-' + l.slice(1))
    .join('\n');

const out = `/* Kite design tokens (light theme), from @tutu/mother-of-tokens ${version}.
   Generated by scripts/build-kite-tokens.js - do not edit by hand. */

:root {
  /* Semantic colours */
${firstRootBlock(read('semantic-colors.scss'))}

  /* Shadows */
${firstRootBlock(read('shadow.scss'))}

  /* Radius, spacing and sizing scales */
${scssScale(read('radius.scss'), 'radius')}
${scssScale(read('spacing.scss'), 'spacing')}
${scssScale(read('sizing.scss'), 'size')}
}
`;

const target = path.resolve(__dirname, '../assets/kite-tokens.css');
fs.writeFileSync(target, out);
console.log(`Wrote ${path.relative(process.cwd(), target)} (${out.length} bytes, tokens ${version})`);
